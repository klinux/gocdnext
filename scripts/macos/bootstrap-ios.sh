#!/usr/bin/env bash
# Prepare a macOS shell agent for native iOS jobs. Xcode itself must already be
# installed from Apple; this script selects it, completes its one-time setup,
# and installs a pinned Ruby toolchain in the build user's home directory.
set -euo pipefail

RUBY_FORMULA="${GOCDNEXT_RUBY_FORMULA:-ruby@3.4}"
BUNDLER_VERSION="${GOCDNEXT_BUNDLER_VERSION:-4.0.24}"
FASTLANE_VERSION="${GOCDNEXT_FASTLANE_VERSION:-2.241.1}"
COCOAPODS_VERSION="${GOCDNEXT_COCOAPODS_VERSION:-1.17.0}"
DEVELOPER_DIR="${GOCDNEXT_XCODE_DEVELOPER_DIR:-/Applications/Xcode.app/Contents/Developer}"
TOOLCHAIN_ROOT="${GOCDNEXT_IOS_TOOLCHAIN_ROOT:-${HOME}/.local/share/gocdnext-ios}"
ENV_FILE="${GOCDNEXT_IOS_ENV_FILE:-${HOME}/.config/gocdnext/ios-toolchain.env}"

die() {
  printf 'error: %s\n' "$*" >&2
  exit 1
}

[ "$(uname -s)" = "Darwin" ] || die "the iOS toolchain bootstrap must run on macOS"
command -v brew >/dev/null 2>&1 || die "Homebrew is required; install it from https://brew.sh first"
command -v xcode-select >/dev/null 2>&1 || die "xcode-select is missing; install full Xcode first"
[ -x "${DEVELOPER_DIR}/usr/bin/xcodebuild" ] || \
  die "full Xcode was not found at ${DEVELOPER_DIR}; set GOCDNEXT_XCODE_DEVELOPER_DIR"

current_developer_dir="$(xcode-select -p 2>/dev/null || true)"
if [ "$current_developer_dir" != "$DEVELOPER_DIR" ]; then
  printf 'Selecting Xcode at %s (sudo required once)\n' "$DEVELOPER_DIR"
  sudo xcode-select --switch "$DEVELOPER_DIR"
fi

# -checkFirstLaunchStatus is silent and non-zero until the license and bundled
# components have been initialized. Never accept a new license implicitly on a
# routine job: this bootstrap is the explicit, operator-run one-time step.
if ! "${DEVELOPER_DIR}/usr/bin/xcodebuild" -checkFirstLaunchStatus >/dev/null 2>&1; then
  printf 'Completing Xcode first-launch setup (sudo required once)\n'
  sudo "${DEVELOPER_DIR}/usr/bin/xcodebuild" -license accept
  sudo "${DEVELOPER_DIR}/usr/bin/xcodebuild" -runFirstLaunch
fi

if ! brew list --versions "$RUBY_FORMULA" >/dev/null 2>&1; then
  brew install "$RUBY_FORMULA"
fi

RUBY_PREFIX="$(brew --prefix "$RUBY_FORMULA")"
RUBY_BIN="${RUBY_PREFIX}/bin"
GEM_HOME="${TOOLCHAIN_ROOT}/gems"
GEM_BIN="${GEM_HOME}/bin"
GEM="${RUBY_BIN}/gem"

[ -x "$GEM" ] || die "Homebrew's ${RUBY_FORMULA} did not provide ${GEM}"
mkdir -p "$GEM_BIN" "$(dirname "$ENV_FILE")"
DEFAULT_GEM_PATH="$("${RUBY_BIN}/ruby" -rrubygems -e 'puts Gem.path.join(":")')"
TOOLCHAIN_GEM_PATH="${GEM_HOME}:${DEFAULT_GEM_PATH}"

gem_installed() {
  local name="$1" version="$2"
  env GEM_HOME="$GEM_HOME" GEM_PATH="$TOOLCHAIN_GEM_PATH" \
    "$GEM" list --local --installed --exact "$name" --version "$version" >/dev/null 2>&1
}

install_gem() {
  local name="$1" version="$2"
  if ! gem_installed "$name" "$version"; then
    env GEM_HOME="$GEM_HOME" GEM_PATH="$TOOLCHAIN_GEM_PATH" \
      "$GEM" install "$name" --version "$version" --no-document \
      --bindir "$GEM_BIN"
  fi
}

install_gem bundler "$BUNDLER_VERSION"
install_gem fastlane "$FASTLANE_VERSION"
install_gem cocoapods "$COCOAPODS_VERSION"

# The LaunchDaemon intentionally has a conservative PATH. Jobs source this
# build-user-owned file to select the pinned, non-system Ruby.
umask 077
tmp_env="${ENV_FILE}.tmp.$$"
trap 'rm -f "$tmp_env"' EXIT
{
  printf '# Generated by gocdnext scripts/macos/bootstrap-ios.sh\n'
  printf 'export PATH=%q\n' "${RUBY_BIN}:${GEM_BIN}:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
  printf 'export GEM_HOME=%q\n' "$GEM_HOME"
  printf 'export GEM_PATH=%q\n' "$TOOLCHAIN_GEM_PATH"
  printf 'export DEVELOPER_DIR=${DEVELOPER_DIR:-%q}\n' "$DEVELOPER_DIR"
} >"$tmp_env"
chmod 600 "$tmp_env"
mv "$tmp_env" "$ENV_FILE"
trap - EXIT

# Verify the executables through the exact environment a shell job will use.
# Version output is intentionally limited to non-secret tool metadata.
# shellcheck disable=SC1090
source "$ENV_FILE"
printf 'Xcode: %s\n' "$(xcodebuild -version | head -1)"
printf 'Ruby: %s\n' "$(ruby --version)"
printf 'Bundler: %s\n' "$(bundle --version)"
printf 'fastlane: %s\n' "$(fastlane --version | tail -1)"
printf 'CocoaPods: %s\n' "$(pod --version)"
printf 'iOS toolchain ready; source %s in native macOS jobs.\n' "$ENV_FILE"
